import assert from 'node:assert/strict';
import {readFile} from 'node:fs/promises';
const load=async file=>import('data:text/javascript;base64,'+Buffer.from(await readFile(new URL('../'+file,import.meta.url))).toString('base64'));
const {customerVisible,broadcastEligible,customerDeletionPatch}=await load('customer-management.js');
const a={id:'customer',status:'active'};
assert.equal(broadcastEligible(a,'owner'),true);
for(const status of ['pending','blocked','archived','revoked'])assert.equal(broadcastEligible({...a,status},'owner'),false);
assert.equal(broadcastEligible({...a,marketingOptIn:false},'owner'),false);
assert.equal(broadcastEligible({...a,id:'owner'},'owner'),false);
assert.equal(broadcastEligible({...a,adminMergedInto:'other'},'owner'),false);
const deleted={...a,...customerDeletionPatch()};
assert.equal(customerVisible(deleted),false);
assert.equal(customerVisible(deleted,'deleted'),true);
assert.equal(broadcastEligible(deleted,'owner'),false);
const restored={...deleted,...customerDeletionPatch(true)};
assert.equal(customerVisible(restored),true);
assert.equal(broadcastEligible(restored,'owner'),false);
assert.equal(broadcastEligible({...restored,status:'active'},'owner'),true);
const {unreadSummary}=await load('salon-unread.js');
assert.equal(unreadSummary([{...deleted,lastCustomerMessageAt:100,readAdminMs:0},{...a,lastCustomerMessageAt:100,readAdminMs:0}]),1);
const {normalizeTheme}=await load('salon-theme.js');
for(const direction of ['top','left','right'])assert.equal(normalizeTheme({greetingDirection:direction}).greetingDirection,direction);
assert.equal(normalizeTheme({greetingDirection:'invalid'}).greetingDirection,'left');
console.log('PASS: reversible removal, approval gating, broadcast exclusions, unread exclusion and greeting direction validation');
